#!/bin/sh
# Этот скрипт автоматически обновляет файл /etc/hosts на роутере OpenWrt
# === START: [2026-11-03] Поддержка пула нескольких IP-адресов (Multi-IP Failover / Dual-Stack) ===
# Использование: sh update_router_hosts.sh [VPS_IP...] [none/off]
# Примеры:
#   sh update_router_hosts.sh 109.120.157.203 186.246.113.160 2a01:e5c0:65c1::2
#   sh update_router_hosts.sh 109.120.157.203,186.246.113.160 2a01:e5c0:65c1::2
#   sh update_router_hosts.sh 109.120.157.203 none

if [ $# -gt 0 ]; then
    RAW_ARGS=$(echo "$*" | tr ',' ' ')
    NEW_IPV4=""
    NEW_IPV6=""
    IPV6_OFF=0

    for item in $RAW_ARGS; do
        case "$item" in
            none|off)
                IPV6_OFF=1
                ;;
            *:*)
                NEW_IPV6="$NEW_IPV6 $item"
                ;;
            *.*)
                NEW_IPV4="$NEW_IPV4 $item"
                ;;
        esac
    done

    NEW_IPV4=$(echo $NEW_IPV4)
    NEW_IPV6=$(echo $NEW_IPV6)

    if [ -n "$NEW_IPV4" ]; then
        echo "$NEW_IPV4" > /etc/sni_proxy_ip
        VPS_IP="$NEW_IPV4"
    elif [ -f /etc/sni_proxy_ip ]; then
        VPS_IP=$(cat /etc/sni_proxy_ip 2>/dev/null)
        VPS_IP=$(echo $VPS_IP)
    else
        echo "Ошибка: не указан IPv4 адрес VPS."
        echo "Использование: $0 <VPS_IPv4...> [VPS_IPv6...] [none/off]"
        exit 1
    fi

    if [ "$IPV6_OFF" -eq 1 ]; then
        rm -f /etc/sni_proxy_ipv6
        VPS_IPV6=""
    elif [ -n "$NEW_IPV6" ]; then
        echo "$NEW_IPV6" > /etc/sni_proxy_ipv6
        VPS_IPV6="$NEW_IPV6"
    elif [ -f /etc/sni_proxy_ipv6 ]; then
        VPS_IPV6=$(cat /etc/sni_proxy_ipv6 2>/dev/null)
        VPS_IPV6=$(echo $VPS_IPV6)
    else
        VPS_IPV6=""
    fi
else
    # Запуск без параметров (cron): считываем сохраненные IP
    if [ -f /etc/sni_proxy_ip ]; then
        VPS_IP=$(cat /etc/sni_proxy_ip 2>/dev/null)
        VPS_IP=$(echo $VPS_IP)
    else
        echo "Ошибка: не указан IPv4 адрес VPS и не найден /etc/sni_proxy_ip."
        echo "Использование: $0 <VPS_IPv4...> [VPS_IPv6...] [none/off]"
        exit 1
    fi

    if [ -f /etc/sni_proxy_ipv6 ]; then
        VPS_IPV6=$(cat /etc/sni_proxy_ipv6 2>/dev/null)
        VPS_IPV6=$(echo $VPS_IPV6)
    else
        VPS_IPV6=""
    fi
fi

TEMPLATE_URL="https://raw.githubusercontent.com/uraz0v/sni-proxy/main/mega_hosts_template.txt"
TMP_TEMPLATE="/tmp/mega_hosts_template.txt"
TMP_NEW="/tmp/hosts_new.txt"
MARKER="# --- SNI PROXY AUTOGENERATED ---"

echo "Скачиваем свежий шаблон с GitHub..."
CURL_OPTS="-sL --connect-timeout 10"
RESOLVE_ADDRS=""
if [ -n "$VPS_IPV6" ]; then
    for ip in $VPS_IPV6; do
        RESOLVE_ADDRS="${RESOLVE_ADDRS:+$RESOLVE_ADDRS,}[$ip]"
    done
fi
for ip in $VPS_IP; do
    RESOLVE_ADDRS="${RESOLVE_ADDRS:+$RESOLVE_ADDRS,}$ip"
done

if [ -n "$RESOLVE_ADDRS" ]; then
    CURL_OPTS="$CURL_OPTS --resolve raw.githubusercontent.com:443:$RESOLVE_ADDRS"
fi

if ! curl $CURL_OPTS -o "$TMP_TEMPLATE" "$TEMPLATE_URL"; then
    if ! wget -q -T 10 -O "$TMP_TEMPLATE" "$TEMPLATE_URL"; then
        echo "Ошибка скачивания файла!"
        exit 1
    fi
fi

if [ ! -s "$TMP_TEMPLATE" ]; then
    echo "Ошибка: скачанный файл пуст."
    exit 1
fi

echo "Подставляем IP серверов (IPv4: $VPS_IP${VPS_IPV6:+, IPv6: $VPS_IPV6})..."

awk -v ip4_list="$VPS_IP" -v ip6_list="$VPS_IPV6" '
BEGIN {
    n4 = split(ip4_list, arr4, " ")
    n6 = split(ip6_list, arr6, " ")
}
{
    if ($1 == "YOUR_VPS_IP") {
        for (i = 1; i <= n4; i++) {
            if (arr4[i] != "") print arr4[i] " " $2
        }
        for (j = 1; j <= n6; j++) {
            if (arr6[j] != "") print arr6[j] " " $2
        }
    } else {
        print $0
    }
}' "$TMP_TEMPLATE" > /tmp/proxy_block.txt
# === END: [2026-11-03] Поддержка пула нескольких IP-адресов (Multi-IP Failover / Dual-Stack) ===

echo "Анализируем текущий /etc/hosts..."
# Извлекаем все строки до нашего маркера (это оригинальные системные записи роутера)
awk -v marker="$MARKER" '{
    if ($0 == marker) exit
    print $0
}' /etc/hosts > /tmp/hosts_base.txt

# Собираем новый файл
cat /tmp/hosts_base.txt > "$TMP_NEW"
echo "$MARKER" >> "$TMP_NEW"
cat /tmp/proxy_block.txt >> "$TMP_NEW"

# Сравниваем новый файл со старым
if cmp -s /etc/hosts "$TMP_NEW"; then
    echo "Обновлений нет. Файл hosts актуален."
    rm "$TMP_TEMPLATE" /tmp/proxy_block.txt "$TMP_NEW" /tmp/hosts_base.txt
else
    echo "Обнаружены изменения! Обновляем /etc/hosts..."
    
    # Делаем бекап по правилам пользователя (одна копия за день)
    CURRENT_DATE=$(date +%Y-%m-%d)
    BACKUP_FILE="/etc/hosts_${CURRENT_DATE}"
    
    if [ ! -f "$BACKUP_FILE" ]; then
        cp /etc/hosts "$BACKUP_FILE"
    fi
    
    # Очищаем место: удаляем ВСЕ остальные бекапы hosts, кроме сегодняшнего
    for f in /etc/hosts_20*; do
        if [ "$f" != "$BACKUP_FILE" ] && [ -f "$f" ]; then
            rm -f "$f"
        fi
    done
    # Удаляем старые форматы бекапов, если они были
    rm -f /etc/hosts.bak.*
    
    mv "$TMP_NEW" /etc/hosts
    echo "Перезапускаем dnsmasq..."
    /etc/init.d/dnsmasq restart
fi

# Устанавливаем задачу в cron, если её еще нет
if ! grep -q "update_router_hosts.sh" /etc/crontabs/root 2>/dev/null; then
    echo "Устанавливаем автообновление в cron (каждый день в 05:00)..."
    echo "0 5 * * * /bin/sh /etc/update_router_hosts.sh 2>&1 | logger -t sni-proxy" >> /etc/crontabs/root
    /etc/init.d/cron restart
fi

echo "✅ Готово!"
